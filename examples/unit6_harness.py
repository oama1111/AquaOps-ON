"""Shared plumbing for the Unit 6 evidence scripts.

`unit6_integration.py` proves the assembled system works end to end;
`unit6_perf.py` measures it. Both need the same three things — a hermetic
throwaway database, a real ``uvicorn`` process, and the derived field-week
laboratory export — so they live here once rather than being copy-pasted and
drifting apart.

The important property is that a run is *hermetic*. Every script points
``AQUAOPS_DB_URL`` at a fresh temporary SQLite file and
``AQUAOPS_EVIDENCE_DIR`` at a temporary directory, so re-running produces the
same transcript from a clean clone instead of accumulating state, and a
measurement can never be an artefact of a previous run.

    from examples.unit6_harness import live_server, field_week_csv
"""

